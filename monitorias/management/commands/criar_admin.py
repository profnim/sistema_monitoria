import os
from django.core.management.base import BaseCommand
from django.contrib.auth.models import User
from django.db import connection

class Command(BaseCommand):
    help = 'Atualiza o banco e cria o superusuário'

    def handle(self, *args, **options):
        with connection.cursor() as cursor:
            # 1. Garante a criação da tabela de horários
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS monitorias_horariomonitoria (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    data date NOT NULL,
                    horario_inicio time NOT NULL,
                    horario_fim time NOT NULL,
                    monitoria_id bigint NOT NULL REFERENCES monitorias_monitoria(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED
                );
            """)

            # 2. Remove colunas antigas de data/horário da tabela principal se elas ainda existirem lá
            for col in ['data', 'horario_inicio', 'horario_fim']:
                try:
                    cursor.execute(f"ALTER TABLE monitorias_monitoria DROP COLUMN IF EXISTS {col};")
                except Exception:
                    pass

        self.stdout.write(self.style.SUCCESS('Banco de dados sincronizado com sucesso.'))

        # 3. Criação ou atualização do Superusuário
        username = os.environ.get('ADMIN_USERNAME', 'Admin')
        email = os.environ.get('ADMIN_EMAIL', 'admin@admin.com')
        password = os.environ.get('ADMIN_PASSWORD')

        if password:
            if not User.objects.filter(username=username).exists():
                User.objects.create_superuser(username, email, password)
                self.stdout.write(self.style.SUCCESS(f'Superusuário "{username}" criado!'))
            else:
                user = User.objects.get(username=username)
                user.set_password(password)
                user.save()
                self.stdout.write(self.style.SUCCESS(f'Senha do usuário "{username}" atualizada!'))